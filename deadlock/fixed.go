// Package deadlock містить практичне застосування аналізу з
// Частини 2 домашньої роботи: той самий дедлок із завдання,
// але як тестована функція, яку потрібно виправити.
//
// Оригінальний баг (для довідки — саме цей код ви аналізуєте у
// deadlock-analysis.md):
//
//	var wg sync.WaitGroup
//	ch := make(chan int)
//	wg.Add(1)
//	go func() {
//	    ch <- 42
//	    wg.Done()
//	}()
//	wg.Wait()       // <-- блокується тут: горутина застрягла на
//	                //     "ch <- 42", бо ніхто ще не читає з ch
//	fmt.Println(<-ch)
package deadlock

// Run повертає 42, отримане від горутини через канал, без дедлоку.
//
// Рішення: видалено WaitGroup (для одного значення не потрібна)
// та змінено порядок операцій — читаємо з каналу ДО будь-якого
// wg.Wait(). Це прерває циклічне очікування: main блокується на
// <-ch, дозволяючи горутині успішно надіслати значення.
func Run() int {
	ch := make(chan int)
	go func() {
		ch <- 42
	}()
	return <-ch
}
